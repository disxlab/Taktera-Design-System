#!/usr/bin/env python3
"""Deterministic distribution of Taktera design tokens. No third-party Python packages required."""
from pathlib import Path
import json,re,sys
from xml.sax.saxutils import escape
BASE=Path(__file__).resolve().parent.parent
D=json.loads((BASE/'src'/'tokens.canonical.json').read_text(encoding='utf-8'))
OUT=BASE/'generated'; (OUT/'avalonia').mkdir(parents=True,exist_ok=True)
PRODUCTS=['platform','clinic','beauty','spa','fitness','travel']
def val(x):
    v=x['$value'] if isinstance(x,dict) and '$value' in x else x
    if isinstance(v,dict) and 'hex' in v:return v['hex']
    return v

def flatten(node,prefix=()):
    if isinstance(node,dict) and '$value' in node:
        yield ('-'.join(prefix),val(node))
    elif isinstance(node,dict):
        for k,v in node.items():
            if not k.startswith('$'):yield from flatten(v,prefix+(k,))
# all brand colors used as source values - no hardcoded hues
brand=D['brand']['color']; semantic=D['semantic']; foundation=D['foundation']; ext=D['extension']
# use separate CSS prefixed variables to avoid modifying v3.3 established variable semantics
css=['/* GENERATED by 25_internal_completion/src/build_tokens.py. DO NOT EDIT. */']
for section in ['spacing','typography','radii']:
    values=dict(flatten(ext[section]));css.append(':root { '+ ' '.join(f'--tkn-{section}-{k}:{v};' for k,v in sorted(values.items()))+' }')
# Density tokens are values; dynamic density selectors override only new names
DENS={'comfortable':('comfortableRow','comfortableControl'),'compact':('compactRow','compactControl')}
for name,(row,control) in DENS.items():
    items=ext['density'];css.append(f'[data-density="{name}"] {{ --tkn-row-height:{val(items[row])}; --tkn-control-height:{val(items[control])}; }}')
for theme in ['light','dark']:
    pairs={**{'foundation-'+k:v for k,v in flatten(foundation['color'][theme])}, **{'semantic-'+k:v for k,v in flatten(semantic['color'][theme])}}
    css.append(f'[data-theme="{theme}"] {{ '+' '.join(f'--tkn-{k}:{v};' for k,v in sorted(pairs.items()))+' }')
for product in PRODUCTS:
    for theme in ['light','dark']:
        pairs=dict(flatten(brand[product][theme]));
        css.append(f'[data-product="{product}"][data-theme="{theme}"] {{ '+' '.join(f'--tkn-brand-{k}:{v};' for k,v in sorted(pairs.items()))+' }')
(OUT/'tokens.web.css').write_text('\n'.join(css)+'\n',encoding='utf-8')
# Font and metrics are dimension/double/int in XAML, color brushes are declared only as colors.
for product in PRODUCTS:
    for theme in ['light','dark']:
        pair=dict(flatten(brand[product][theme]))
        n=f'{product.title()}.{theme.title()}'
        lines=['<?xml version="1.0" encoding="utf-8"?>',f'<!-- GENERATED. Product {product}, theme {theme}; resources only, not executable ControlTheme. -->','<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">']
        for k,v in sorted(pair.items()):
            if isinstance(v,str) and re.fullmatch('#[0-9a-fA-F]{6,8}',v):
                key='TknBrand'+''.join(s.title() for s in k.split('-'))
                lines.append(f'  <Color x:Key="{key}Color">{v}</Color>')
                lines.append(f'  <SolidColorBrush x:Key="{key}Brush" Color="{v}"/>')
        for source_name,source in [('Foundation',foundation['color'][theme]),('Semantic',semantic['color'][theme])]:
            for k,v in sorted(flatten(source)):
                if isinstance(v,str) and re.fullmatch('#[0-9a-fA-F]{6,8}',v):
                    key='Tkn'+source_name+''.join(part.title() for part in k.split('-'))
                    lines.append(f'  <Color x:Key="{key}Color">{v}</Color>')
                    lines.append(f'  <SolidColorBrush x:Key="{key}Brush" Color="{v}"/>')
        for section in ['spacing','typography','radii']:
            for k,v in sorted(flatten(ext[section])):
                if isinstance(v,str) and v.endswith('px'):
                    key='Tkn'+section.title()+k.title()
                    lines.append(f'  <x:Double x:Key="{key}">{float(v[:-2]):g}</x:Double>')
        for density,(row,control) in DENS.items():
            lines.append(f'  <x:Double x:Key="Tkn{density.title()}RowHeight">{float(val(ext["density"][row])[:-2]):g}</x:Double>')
            lines.append(f'  <x:Double x:Key="Tkn{density.title()}ControlHeight">{float(val(ext["density"][control])[:-2]):g}</x:Double>')
        lines.append('</ResourceDictionary>')
        (OUT/'avalonia'/f'Taktera.{n}.axaml').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('generated',len(PRODUCTS)*2,'Avalonia themes and Web CSS')
