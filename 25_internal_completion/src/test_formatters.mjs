import assert from 'node:assert/strict';
import {formatDate,formatCurrency,formatNumber,formatPercent,pluralize,t} from './formatters.mjs';
assert.match(formatDate('2026-11-23','ru-RU'),/23.*ноября.*2026/);
assert.match(formatDate('2026-11-23','en-US'),/November 23, 2026/);
assert.match(formatCurrency(1234567.5,'RUB','ru-RU'),/1\s?234\s?567|1.234.567|1 234 567/);
assert.match(formatCurrency(1234.5,'USD','en-US'),/\$1,234\.50/);
assert.equal(pluralize(1,'task','ru-RU'),'1 задача');
assert.equal(pluralize(2,'task','ru-RU'),'2 задачи');
assert.equal(pluralize(5,'task','ru-RU'),'5 задач');
assert.equal(pluralize(21,'task','ru-RU'),'21 задача');
assert.equal(pluralize(2,'client','en-US'),'2 clients');
assert.equal(t('search','en-US'),'Search');
assert.throws(()=>formatDate('not-a-date'),RangeError);
assert.throws(()=>formatCurrency(NaN),RangeError);
assert.throws(()=>pluralize(3,'unknown'),RangeError);
assert.throws(()=>t('invalid'),RangeError);
assert.ok(formatNumber(12.5,'en-US').includes('12.5'));
assert.ok(formatPercent(.125,'en-US').includes('12.5'));
console.log('PASS: 15 formatter assertions');
