#!/usr/bin/env python3
"""Promote no packages: verify matching independent CI runs and stage canonical test inputs."""
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

def require(ok, message):
    if not ok:
        raise ValueError(message)

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def read(path):
    return json.loads(path.read_text(encoding="utf-8"))

def write(path, value):
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")

def verify(root, source):
    report = read(root / "report.json")
    require(report["source"] == source and report["passed"] is True and report["errors"] == [],
            "Unsuccessful or foreign reproducibility report")
    require(len(report["builds"]) == 2 and len(report["comparisons"]) == 3,
            "Incomplete reproducibility report")
    require(report["compilerStages"]["before-xaml.dll"]["identical"] is True
            and report["compilerStages"]["after-xaml.dll"]["identical"] is True,
            "Compiler-stage mismatch")
    packages = {}
    for entry in report["comparisons"]:
        name = entry["file"]
        require(re.fullmatch(r"[A-Za-z0-9._-]+\.(?:tgz|nupkg)", name) is not None,
                "Unsafe package filename")
        require(name not in packages and entry["identical"] is True, "Duplicate or unequal package")
        digest = entry["sha256A"]
        require(entry["sha256B"] == digest == sha(root / "a" / name) == sha(root / "b" / name),
                "Archive digest mismatch: " + name)
        packages[name] = digest
    require(sum(n.endswith(".nupkg") for n in packages) == 1
            and sum(n.endswith(".tgz") for n in packages) == 2, "Unexpected package types")
    for build in report["builds"]:
        require(build["packages"] == packages, "Build inventory mismatch")
    require(report["toolchain"]["node"] == "v26.13.1"
            and report["toolchain"]["npm"] == "11.20.0"
            and report["toolchain"]["dotnet"] == "10.0.404", "Unexpected toolchain")
    lock = read(root / "packages.lock.json")
    require(isinstance(lock.get("dependencies"), dict) and lock["dependencies"], "Missing NuGet lock")
    return packages, report, lock

def main(a, b, out):
    source = subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()
    pa, ra, la = verify(a, source)
    pb, rb, lb = verify(b, source)
    require(pa == pb, "Independent runners produced different packages")
    require(la == lb, "Independent runners resolved different NuGet locks")
    require(ra["toolchain"] == rb["toolchain"], "Independent runner toolchains differ")
    out.mkdir(parents=True, exist_ok=False)
    for name, digest in pa.items():
        shutil.copyfile(a / "a" / name, out / name)
        require(sha(out / name) == digest, "Canonical copy changed")
    shutil.copyfile(a / "packages.lock.json", out / "packages.lock.json")
    shutil.copyfile(a / "report.json", out / "repro-primary.json")
    shutil.copyfile(b / "report.json", out / "repro-secondary.json")
    manifest = {"source": source, "packages": pa, "nugetLockSha256": sha(out / "packages.lock.json"),
                "independentRunnerJobs": 2, "cleanBuilds": 4, "published": False}
    write(out / "canonical.json", manifest)
    # The lock is public dependency metadata generated by restore, not a fabricated lock.
    # Emit the exact JSON as evidence for later reviewed source control inclusion.
    print("TAKTERA_NUGET_LOCK_BEGIN")
    print((out / "packages.lock.json").read_text(encoding="utf-8"), end="\n")
    print("TAKTERA_NUGET_LOCK_END")
    print(json.dumps(manifest, sort_keys=True))

if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit("usage: verify_canonical.py primary secondary output")
    main(*(Path(p) for p in sys.argv[1:]))
